function FaqRow({
  section,
  open,
  onToggle,
}: {
  section: FaqSection;
  open: boolean;
  onToggle: () => void;
}) {
  return (
    <div
      className={cn(
        "rounded-card border border-border bg-panel overflow-hidden transition-colors",
        open && "border-accent/40",
      )}
    >
      <button
        type="button"
        onClick={onToggle}
        aria-expanded={open}
        className="w-full flex items-center gap-3 px-4 py-3 text-left active:opacity-80 transition"
      >
        <ChevronDown
          className={cn(
            "size-4 shrink-0 text-text-muted transition-transform",
            open ? "rotate-0 text-accent" : "-rotate-90",
          )}
          strokeWidth={2}
        />
        <span className="flex-1 text-[14px] font-medium text-text">
          {section.title}
        </span>
      </button>
      <div
        className={cn(
          "grid transition-[grid-template-rows] duration-200 ease-out",
          open ? "grid-rows-[1fr]" : "grid-rows-[0fr]",
        )}
      >
        <div className="overflow-hidden">
          <div className="px-4 pb-4 pt-1 space-y-2 text-[13px] leading-relaxed text-text-muted">
            {section.body.map((p, i) => (
              <p key={i}>{p}</p>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}

function StaffSection({
  title,
  icon,
  isLoading,
  isError,
  people,
}: {
  title: string;
  icon: React.ReactNode;
  isLoading: boolean;
  isError: boolean;
  people: SupportPersonDto[] | undefined;
}) {
  return (
    <div>
      <div className="flex items-center gap-2 px-1 mb-2">
        <span className="text-accent">{icon}</span>
        <h2 className="text-[14px] font-semibold tracking-tight text-text">
          {title}
        </h2>
      </div>
      {isLoading ? (
        <div className="rounded-card border border-border bg-panel p-3 text-[13px] text-text-muted">
          Загружаем…
        </div>
      ) : isError ? (
        <div className="rounded-card border border-border bg-panel p-3 text-[13px] text-text-muted">
          Не удалось загрузить список.
        </div>
      ) : !people || people.length === 0 ? (
        <div className="rounded-card border border-border bg-panel p-3 text-[13px] text-text-muted">
          Список пуст.
        </div>
      ) : (
        <div className="space-y-2">
          {people.map((p, i) => (
            <SupportPersonRow key={p.id} person={p} index={i} />
          ))}
        </div>
      )}
    </div>
  );
}

